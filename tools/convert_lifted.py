"""Mechanical C# -> C++ conversion of GjkSimplexSolver.Lifted.cs (lifted x87 code of sub_595040).

usage: python convert_lifted.py <in.cs> <out.cpp>
"""
import re
import sys


def balanced(s, i):
    """s[i] == '(' -> index of the matching ')'."""
    depth = 0
    for j in range(i, len(s)):
        if s[j] == '(':
            depth += 1
        elif s[j] == ')':
            depth -= 1
            if depth == 0:
                return j
    raise ValueError("unbalanced: " + s)


OPS = ['<<', '>>', '+', '-', '^', '&', '|', '*']


def split_top(expr):
    """Top-level binary operator split (left-most lowest-precedence is not needed: the lifter emits one op)."""
    depth = 0
    i = 0
    while i < len(expr):
        c = expr[i]
        if c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
        elif depth == 0 and i > 0:
            for op in OPS:
                if expr.startswith(op, i) and expr[i - 1] == ' ':
                    return expr[:i].strip(), op, expr[i + len(op):].strip()
        i += 1
    return None


def conv_unchecked(s):
    while True:
        k = s.find('unchecked(')
        if k < 0:
            return s
        o = k + len('unchecked')
        e = balanced(s, o)
        inner = conv_unchecked(s[o + 1:e])
        sp = split_top(inner)
        if sp is None:
            rep = '(' + inner + ')'
        else:
            l, op, r = sp
            if op == '<<':
                rep = '(int)((uint32_t)(%s) << (%s))' % (l, r)
            elif op == '>>':
                rep = '((%s) >> (%s))' % (l, r)
            else:
                rep = '(int)((uint32_t)(%s) %s (uint32_t)(%s))' % (l, op, r)
        s = s[:k] + rep + s[e + 1:]


def main():
    src = open(sys.argv[1], encoding='utf-8').read().splitlines()
    out = []
    out.append('// <auto-generated>')
    out.append('// C++ conversion (tools/convert_lifted.py) of NFSU2Unity Core/Physics/Collision/GjkSimplexSolver.Lifted.cs,')
    out.append('// itself lifted from SPEED2.EXE v1.2 0x00595040 by tools/harness/lift_x87.py: GJK simplex solver sub_595040')
    out.append('// (closest features of the A/B simplices). Literal instruction-by-instruction translation (x87 stack slots are')
    out.append('// F24 locals s0..s7, integer registers are ints with 32-bit wrap-around, memory is the word array M).')
    out.append('// Do not edit by hand: regenerate instead.')
    out.append('// </auto-generated>')
    out.append('#include "drive/physics/collision/GjkSimplexSolver.h"')
    out.append('')
    out.append('#include "drive/numerics/BWareMath.h"')
    out.append('#include "drive/numerics/X87.h"')
    out.append('')
    out.append('#include <cstdint>')
    out.append('')
    out.append('#ifdef _MSC_VER')
    out.append('#pragma warning(disable : 4102 4189 4101 4702)')
    out.append('#endif')
    out.append('')
    out.append('namespace bb {')
    out.append('')
    in_body = False
    for line in src:
        st = line.strip()
        if not in_body:
            m = re.match(r'static readonly float (K_\w+) = X87\.Bits\((0x[0-9A-Fa-f]+u)\);(.*)', st)
            if m:
                out.append('static const float %s = X87::Bits(%s);%s' % m.groups())
                continue
            if st.startswith('static F24 Lifted('):
                out.append('')
                out.append('F24 GjkSimplexSolver::Lifted(uint32_t* M, int ecx, int esp)')
                in_body = True
                depth = 0
                continue
            continue
        # body
        l = line
        if l.startswith('        '):
            l = l[8:]
        l = conv_unchecked(l)
        l = l.replace('X87.', 'X87::').replace('BWareMath2.', 'BWareMath2::').replace('F24.', 'F24::')
        l = l.replace('{ var t = ', '{ auto t = ')
        l = l.replace(', out ecx)', ', ecx)')
        l = re.sub(r'(s[0-7]) = default', r'\1', l)
        if 'unchecked' in l or ' out ' in l or 'var ' in l:
            raise ValueError('unconverted: ' + line)
        depth += l.count('{') - l.count('}')
        out.append(l)
        if depth == 0 and st == '}':
            break
    out.append('')
    out.append('} // namespace bb')
    out.append('')
    open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out))


if __name__ == '__main__':
    main()
